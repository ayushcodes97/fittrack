// Regenerates src/data/foodImages.ts from public/images/foods/credits.json
// and the jpg files actually present, ordered by src/data/foods.ts ids.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const OUT = join(process.cwd(), 'public', 'images', 'foods')
const credits = JSON.parse(readFileSync(join(OUT, 'credits.json'), 'utf8')).credits
// food order from src/data/foods.ts keeps the mapping readable and consistent
const foods = readFileSync(join(process.cwd(), 'src', 'data', 'foods.ts'), 'utf8')
const ids = [...foods.matchAll(/id: '([^']+)'/g)].map((m) => m[1])
const jpgs = new Set(readdirSync(OUT).filter((f) => f.endsWith('.jpg')).map((f) => f.replace('.jpg', '')))

const mapping = {}
const used = {}
for (const id of ids) {
  if (jpgs.has(id)) mapping[id] = `/images/foods/${id}.jpg`
  if (credits[id]) used[id] = credits[id]
}
const missing = ids.filter((id) => !mapping[id])
const noCredit = ids.filter((id) => mapping[id] && !used[id])

const ts = `/** Centralized food image mapping. Generated by scripts/gen-food-images.mjs — do not edit by hand.
 *  All images are real photographs stored locally under /images/foods/. */

export interface FoodImageCredit {
  source: string
  sourceUrl?: string
  author?: string
  license?: string
}

export const FOOD_IMAGES: Record<string, string> = ${JSON.stringify(mapping, null, 2)}

export const FOOD_IMAGE_CREDITS: Record<string, FoodImageCredit> = ${JSON.stringify(used, null, 2)}

export const FOOD_IMAGE_FALLBACK = '/images/foods/placeholder.svg'
`
writeFileSync(join(process.cwd(), 'src', 'data', 'foodImages.ts'), ts)
console.log(`mapped: ${Object.keys(mapping).length} | missing images: ${missing.join(',') || 'none'} | credits missing: ${noCredit.join(',') || 'none'}`)
